-- Run this in Supabase: SQL Editor → New query → Run
create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  product text not null,
  message text,
  created_at timestamptz not null default now()
);

alter table public.enquiries enable row level security;

-- Visitors can submit an enquiry, but cannot read customer records.
drop policy if exists "Anyone can submit an enquiry" on public.enquiries;
create policy "Anyone can submit an enquiry"
on public.enquiries
for insert
to anon, authenticated
with check (
  length(trim(customer_name)) between 1 and 80
  and length(trim(phone)) between 1 and 20
  and length(trim(product)) between 1 and 160
  and (message is null or length(message) <= 1000)
);

-- Intentionally no SELECT policy for anon visitors.
-- The boutique owner can view records after signing into the Supabase dashboard.
